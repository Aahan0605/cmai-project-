"""Grouped cross-validation over identity components (Gate 1 recommendation 2).

With 4 test people, `baseline_timit_v3` could not separate any optimizer. Here the identity
components (for OptLab-TIMIT, the 16 face-swap pairs) are dealt into K folds. Fold k is the
test set, fold k+1 supplies validation (half its components, by clip count, for tuning and
half for fusion), and the remaining folds train, so every person is tested exactly once and train,
validation and test never share a person.

Each fold is an ordinary experiment (`<name>_f<k>`) with its own manifests and generated
config, so tune / train / fuse / evaluate and the test-write guard work unchanged.
"""

from __future__ import annotations

import random
from pathlib import Path

import yaml

from optlab.config import ExperimentConfig
from optlab.data.manifest import (
    VideoRow,
    _assign,
    identity_components,
    read_manifest,
    write_manifest,
)


def fold_assignment(rows: list[VideoRow], n_folds: int, seed: int) -> list[list[list[int]]]:
    """Components (lists of row indices) dealt round-robin into folds after a seeded shuffle."""
    if n_folds < 3:
        raise ValueError("at least three folds are needed for train, validation and test")
    comps = identity_components(rows)
    if len(comps) < 2 * n_folds:
        raise ValueError(f"{len(comps)} identity components cannot fill {n_folds} folds")
    random.Random(seed).shuffle(comps)
    return [comps[k::n_folds] for k in range(n_folds)]


def write_folds(
    base: ExperimentConfig, n_folds: int, seed: int, out_manifests: Path, out_configs: Path
) -> list[Path]:
    """Fold manifests for every dataset the experiment uses, plus one config per fold.

    All datasets must list the same identities (as OptLab-TIMIT HQ / LQ do), so one fold
    assignment, computed on the training dataset, applies to all of them.
    """
    datasets = [base.train_dataset, base.eval.in_distribution, *base.eval.cross_dataset]
    datasets = list(dict.fromkeys(datasets))
    manifests = {d: read_manifest(Path(base.manifests_dir) / f"{d}.csv") for d in datasets}
    train_rows = manifests[base.train_dataset]
    folds = fold_assignment(train_rows, n_folds, seed)
    # Map every identity to its fold through the training manifest's components.
    fold_of: dict[str, int] = {}
    for k, comps in enumerate(folds):
        for comp in comps:
            for i in comp:
                for ident in train_rows[i].identity_id.split("+"):
                    fold_of[ident] = k
    for dataset, rows in manifests.items():
        identities = {ident for row in rows for ident in row.identity_id.split("+")}
        if identities != set(fold_of):
            raise ValueError(f"{dataset}: CV datasets must contain the same identities")
        for row in rows:
            if len({fold_of[ident] for ident in row.identity_id.split("+")}) != 1:
                raise ValueError(f"{dataset}: identity component crosses folds")
    paths = []
    for k in range(n_folds):
        val_k = (k + 1) % n_folds
        role_of = _assign(folds[val_k], {"tune": 0.5, "fusion": 0.5}, random.Random(seed + k))
        tune_ids = {
            ident
            for i, role in role_of.items()
            if role == "tune"
            for ident in train_rows[i].identity_id.split("+")
        }
        for role in ("tune", "fusion"):
            labels = {train_rows[i].label for i, r in role_of.items() if r == role}
            if labels != {0, 1}:
                raise ValueError(f"fold {k}: val_{role} lacks a class ({labels}); use fewer folds")
        fold_dir = out_manifests / f"f{k}"
        for d, rows in manifests.items():
            out = []
            for r in rows:
                f = fold_of[r.identity_id.split("+")[0]]
                split = "test" if f == k else "val" if f == val_k else "train"
                role = (
                    ("tune" if r.identity_id.split("+")[0] in tune_ids else "fusion")
                    if split == "val"
                    else ""
                )
                out.append(
                    VideoRow(r.video_id, r.path, r.label, r.method, r.identity_id, split, role)
                )
            write_manifest(out, fold_dir / f"{d}.csv")
        cfg = base.model_copy(
            update={
                "name": f"{base.name}_f{k}",
                "manifests_dir": fold_dir.as_posix(),
                "description": f"Fold {k} of {n_folds} of {base.name}. " + (base.description or ""),
            }
        )
        path = out_configs / f"{base.name}_f{k}.yaml"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            "# Generated by `optlab cv`; edit the base config instead.\n"
            + yaml.safe_dump(cfg.model_dump(mode="json"), sort_keys=False)
        )
        paths.append(path)
    return paths
